"""
SIMULATION 2: Full 3D Turbulent Wind Tunnel CFD Analysis (OpenFOAM)
===================================================================
Tools: OpenFOAM (blockMesh + surfaceFeatureExtract + snappyHexMesh + simpleFoam)
       with k-omega SST RANS turbulence model on the actual 3D watertight STL
       of FREE-ROOM D12-500 (generated by SIM-1).

Loads evaluated:
  - Design steady wind: U_ref = 20.0 m/s (72 km/h, Beaufort 8-9 gale)
  - Extreme 3-sec gust: U_gust = 25.0 m/s (90 km/h, Beaufort 10 storm)
  - Extracts real 3D aerodynamic drag F_D, lift F_L, overturning moment M_y,
    coefficients C_d, C_L, and azimuth-resolved surface pressure coefficients C_p
    for one-way Fluid-Structure Interaction (FSI) coupling into CalculiX FEA (SIM-3).

Strict Pass Criteria:
  1. OpenFOAM 3D snappyHexMesh & simpleFoam steady RANS solver converge cleanly
     (residuals < 1e-3, forces stabilized).
  2. Aerodynamic drag coefficient C_d <= 0.85 (circular/dodecagonal streamlined advantage
     vs rectangular box C_d ~ 1.35).
  3. Aerodynamic roof uplift coefficient C_L <= 0.65 (bounded suction).
  4. Surface pressure distribution validated against AIJ-RLB (Architectural Institute
     of Japan) wind load standards for low-rise cylindrical/conical structures.
"""

